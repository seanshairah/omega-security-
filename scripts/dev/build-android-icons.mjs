/**
 * Generates android/app/src/main/res/drawable/ic_*.xml from @material-symbols/svg-400 (Apache-2.0),
 * the same source and style (rounded, weight 400) the portal uses in scripts/dev/build-icons.mjs.
 *
 * Before this, the phone shipped hand-copied legacy Material Icons on a 24dp viewport while the
 * portal had moved to Material Symbols on a 960 viewport. The same idea — a shield, a missed call,
 * a location — was drawn differently in the two halves of the product.
 *
 * Material Symbols are authored on a 960x960 grid with the origin at the top of a -960..0 y range,
 * which is why the generated vectors carry viewportHeight 960 and a translate: Android has no
 * negative viewport origin.
 *
 * Run after changing ICONS:  node scripts/dev/build-android-icons.mjs
 */
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.dirname(require.resolve("@material-symbols/svg-400/package.json"));
const STYLE = "rounded";
const OUT = path.join(process.cwd(), "android/app/src/main/res/drawable");

/**
 * drawable name -> [Material Symbols name, filled?]
 *
 * Every name the app already referenced is kept, so no layout or Kotlin reference breaks. The
 * right-hand side is the concept, chosen to match how the portal uses the same symbol.
 */
const ICONS = {
  // Status and outcome
  ic_check: ["check", false],
  ic_check_circle: ["check_circle", true],
  ic_alert: ["warning", true],
  ic_exclaim: ["error", true],
  ic_thumb_up: ["thumb_up", true],
  ic_shield: ["shield", true],
  ic_lock: ["lock", true],
  ic_pause: ["pause_circle", true],

  // Navigation and chrome
  ic_back: ["arrow_back", false],
  ic_chevron: ["chevron_right", false],
  ic_more: ["more_vert", true],
  ic_doc: ["article", true],

  // Communications
  ic_phone: ["call", true],
  ic_phone_android: ["mobile", true],
  ic_people: ["groups", true],

  // Location
  ic_place: ["location_on", true],
  ic_my_location: ["my_location", true],

  // Device and connectivity
  ic_cellular: ["signal_cellular_alt", true],
  ic_offline: ["cloud_off", true],
  ic_wifi: ["wifi", true],
  ic_warning: ["warning", true],
  ic_sync: ["sync", false],
  ic_bolt: ["bolt", true],
  ic_clock: ["schedule", true],

  // Notification tray icon: must read at 24dp in a single colour.
  ic_stat_gateway: ["shield", true],

  // Permission state. These replace the "✅" / "⬜" text glyphs, which rendered
  // differently on every device font and read aloud as "white large square".
  ic_perm_granted: ["check_circle", true],
  ic_perm_pending: ["radio_button_unchecked", false],
};

function pathData(name, filled) {
  const file = path.join(root, STYLE, `${name}${filled ? "-fill" : ""}.svg`);
  const svg = readFileSync(file, "utf8");
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length) throw new Error(`no path data in ${file}`);
  return ds.join(" ");
}

function drawable(d) {
  // android:tint with colorControlNormal keeps every icon themable from the Kotlin side, which is
  // how the existing ones behaved; losing it would make them all black on a dark surface.
  return `<!-- GENERATED by scripts/dev/build-android-icons.mjs. Do not edit.
     Material Symbols, © Google, Apache License 2.0. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960"
    android:tint="?attr/colorControlNormal">
    <group android:translateY="960">
        <path android:fillColor="@android:color/white" android:pathData="${d}" />
    </group>
</vector>
`;
}

let written = 0;
for (const [drawableName, [symbol, filled]] of Object.entries(ICONS)) {
  writeFileSync(path.join(OUT, `${drawableName}.xml`), drawable(pathData(symbol, filled)));
  written++;
}

// Report any ic_* drawable the app still has that this generator does not own, so a hand-drawn
// leftover cannot sit unnoticed beside the generated set.
const unmanaged = readdirSync(OUT)
  .filter((f) => f.startsWith("ic_") && f.endsWith(".xml"))
  .map((f) => f.replace(/\.xml$/, ""))
  .filter((n) => !(n in ICONS) && !n.startsWith("ic_launcher"));

console.log(`wrote ${written} drawables from Material Symbols (${STYLE}, 400) to ${path.relative(process.cwd(), OUT)}`);
if (unmanaged.length) console.log(`not generated (still hand-drawn): ${unmanaged.join(", ")}`);
