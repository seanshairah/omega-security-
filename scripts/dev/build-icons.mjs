/**
 * Generates src/components/ui/icons.generated.ts from @material-symbols/svg-400 (Apache-2.0).
 * Only the curated names below are emitted, as raw path data (outline + filled), so the app ships
 * a few dozen paths instead of an icon font or a whole library. Run after changing NAMES:
 *   node scripts/dev/build-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = path.dirname(require.resolve("@material-symbols/svg-400/package.json"));
const STYLE = "rounded";

// Grouped by concept so additions stay consistent with what is already used.
const NAMES = {
  navigation: ["home", "menu", "search", "manage_search", "settings", "logout", "chevron_right", "keyboard_arrow_up", "keyboard_arrow_down", "keyboard_double_arrow_left", "keyboard_double_arrow_right", "close", "open_in_new", "more_vert", "arrow_back", "add", "filter_list", "tune", "history", "expand_content", "collapse_content"],
  people: ["groups", "person", "person_off", "manage_accounts", "badge", "shield_person", "apartment"],
  operations: ["sensors", "verified_user", "gpp_maybe", "shield", "report", "warning", "error", "info", "help", "check", "check_circle", "cancel", "flag", "e911_emergency", "medical_services", "visibility", "campaign", "security"],
  location: ["location_on", "location_off", "wrong_location", "where_to_vote", "my_location", "location_searching", "directions_run", "map", "satellite_alt", "layers", "fit_screen", "route", "radar", "pin_drop", "distance", "near_me", "share_location", "travel_explore"],
  time: ["schedule", "calendar_today", "event_available", "event_busy", "timer", "hourglass_top", "pending"],
  comms: ["call", "phone_in_talk", "phone_callback", "phone_forwarded", "phone_missed", "call_end", "sms", "chat", "forum", "mail", "send", "notifications", "notifications_active", "notifications_off", "dialpad"],
  device: ["mobile", "devices", "cell_tower", "signal_cellular_alt", "signal_cellular_off", "wifi_off", "battery_full", "battery_5_bar", "battery_3_bar", "battery_1_bar", "battery_alert", "bolt", "cloud_off", "cloud_done", "sync", "refresh"],
  data: ["bar_chart", "trending_up", "trending_down", "north_east", "south_west", "assignment", "article", "sticky_note_2", "swap_horiz", "content_copy", "download", "edit", "delete", "play_arrow", "fast_forward"],
};

const all = [...new Set(Object.values(NAMES).flat())].sort();
const pathOf = (file) => {
  const svg = readFileSync(path.join(root, STYLE, file), "utf8");
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length) throw new Error(`no path in ${file}`);
  return ds.join(" ");
};
const lines = all.map((n) => `  ${JSON.stringify(n)}: [${JSON.stringify(pathOf(`${n}.svg`))}, ${JSON.stringify(pathOf(`${n}-fill.svg`))}],`);
const out = `// GENERATED by scripts/dev/build-icons.mjs from @material-symbols/svg-400 (${STYLE}, weight 400). Do not edit.
// Material Symbols are © Google, licensed under the Apache License 2.0.
/* eslint-disable */
export const ICON_PATHS = {
${lines.join("\n")}
} as const;
export type IconName = keyof typeof ICON_PATHS;
`;
writeFileSync(new URL("../../src/components/ui/icons.generated.ts", import.meta.url), out);
console.log(`${all.length} icons, ${(out.length / 1024).toFixed(1)} KB`);
